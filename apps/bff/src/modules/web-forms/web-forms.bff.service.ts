import { Injectable, Logger } from '@nestjs/common'
import { ApiCoreGrpcClient } from '../../common/grpc/api-core-grpc.client'
import type { CreateWebForm, UpdateWebForm, WebForm } from '@crm/contracts'

const DEFAULT_TENANT_ID = '00000000-0000-0000-0000-000000000001'

@Injectable()
export class WebFormsBffService {
  private readonly logger = new Logger(WebFormsBffService.name)

  constructor(private readonly api: ApiCoreGrpcClient) {}

  async list(tenantId?: string): Promise<WebForm[]> {
    const tid = tenantId || DEFAULT_TENANT_ID
    return this.api.listWebForms(tid)
  }

  async getById(id: string, tenantId?: string): Promise<WebForm> {
    const tid = tenantId || DEFAULT_TENANT_ID
    return this.api.getWebFormById(tid, id)
  }

  async getPublicForm(idOrSlug: string): Promise<WebForm> {
    return this.api.getPublicWebForm(idOrSlug)
  }

  async create(dto: CreateWebForm, tenantId?: string): Promise<WebForm> {
    const tid = tenantId || DEFAULT_TENANT_ID
    return this.api.createWebForm({
      ...dto,
      tenantId: tid,
    })
  }

  async update(id: string, dto: UpdateWebForm, tenantId?: string): Promise<WebForm> {
    const tid = tenantId || DEFAULT_TENANT_ID
    return this.api.updateWebForm({
      ...dto,
      id,
      tenantId: tid,
    })
  }

  async delete(id: string, tenantId?: string): Promise<void> {
    const tid = tenantId || DEFAULT_TENANT_ID
    await this.api.deleteWebForm(tid, id)
  }

  async submitPublic(idOrSlug: string, formData: Record<string, any>, ip?: string, userAgent?: string) {
    const res = await this.api.submitPublicWebForm({
      idOrSlug,
      formData,
      ipAddress: ip,
      userAgent,
    })

    // Automatically create Contact via gRPC if contactPayload was generated by use case
    let contactId: string | null = null
    if (res.contactPayload) {
      try {
        const contact = await this.api.createContact(res.contactPayload)
        contactId = contact.id
      } catch (err: any) {
        this.logger.warn(`Could not create contact for webform submission: ${err.message}`)
      }
    }

    return {
      success: res.success,
      message: res.message,
      redirectUrl: res.redirectUrl,
      contactId,
    }
  }

  async listSubmissions(formId: string, tenantId?: string) {
    const tid = tenantId || DEFAULT_TENANT_ID
    return this.api.listWebFormSubmissions(tid, formId)
  }
}
